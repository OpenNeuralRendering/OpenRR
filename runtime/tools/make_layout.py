"""Writes gpu/src/dlssd_layout_<version>.inc: where the rr2 weight table, the inline scalars and the noise LUT
sit in one nvngx_dlssd.dll build (file offsets and sizes only, plus a SHA-256 of those bytes so the runtime can tell
that a player's DLL has them at the same places). Nothing of the DLL's content goes into the file.

usage: python runtime/tools/make_layout.py out/map-<version>/map.json
The map comes from tools/dlssd_map.py (master checkout).
"""
import hashlib, json, os, sys

LUT = (0x737350, 4096)          # .rdata noise LUT copied to the head of upload 0 (FASE3A section 2)


def imm_offsets(data, t, rva2off, fbeg, fend):
    """File offset of each inline immediate of the table-building function (unique inside it)."""
    o0, o1 = rva2off(fbeg), rva2off(fend)
    out = []
    for s in t["inline_imm_stores"]:
        n, v = s["size"], int(s["value"], 16)
        pat = v.to_bytes(n, "little")
        hits, i = [], data.find(pat, o0)
        while 0 <= i < o1:
            hits.append(i)
            i = data.find(pat, i + 1)
        assert len(hits) == 1, (s, hits)
        out.append((int(s["slot"], 16), n, hits[0]))
    return out


def main(map_path):
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "..",
                                    "OpenNR-Denoiser", "tools"))
    from dlssd_map import PE
    m = json.load(open(map_path))
    pe = PE(m["path"])
    data = pe.data
    t = m["tables"][0]
    f0 = int(t["func_rva"], 16)
    fend = min(e for b, e in pe.functions() if b <= f0 < e)
    recs = [(int(r["slot"], 16), r["count"], int(r["file_offset"], 16)) for r in t["records"]]
    imms = imm_offsets(data, t, pe.rva2off, f0, fend)
    h = hashlib.sha256()
    for _, n, off in recs:
        h.update(data[off:off + 2 * n])
    for _, n, off in imms:
        h.update(data[off:off + n])
    h.update(data[LUT[0]:LUT[0] + LUT[1]])
    ver = m["version"]
    name = ver.replace(".", "_")
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "gpu", "src", "dlssd_layout_%s.inc" % name)
    with open(out, "w", newline="\n") as f:
        f.write("// SPDX-License-Identifier: MIT\n")
        f.write("// nvngx_dlssd.dll %s: places of the rr2 weight table (slot, fp16 count, file offset), of the inline\n" % ver)
        f.write("// scalars (slot, bytes, file offset) and of the noise LUT. Generated by runtime/tools/make_layout.py.\n")
        f.write("static const LayoutRecord kRecords_%s[] = {\n" % name)
        for s, n, off in recs:
            f.write("    {0x%x, %d, 0x%x},\n" % (s, n, off))
        f.write("};\nstatic const LayoutRecord kImms_%s[] = {\n" % name)
        for s, n, off in imms:
            f.write("    {0x%x, %d, 0x%x},\n" % (s, n, off))
        f.write("};\nstatic const DllLayout kLayout_%s = {\"%s\", kRecords_%s, %d, kImms_%s, %d, 0x%x, %d,\n    \"%s\"};\n"
                % (name, ver, name, len(recs), name, len(imms), LUT[0], LUT[1], h.hexdigest()))
    print("wrote", out, len(recs), "records", len(imms), "immediates")


if __name__ == "__main__":
    main(sys.argv[1])
